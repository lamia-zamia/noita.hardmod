#!/usr/bin/node
/**
 * Build script for Noita Hard Mod
 * 
 * This requires the `sharp` library.
 * Go `cd scripts` and run `npm i` to install it
 * 
 * Usage:
 * $ node scripts/build.js
 * 
 * For a full mod release:
 * $ node scripts/build.js --release
 * 
 * Passing --release will update stuff we don't want/need to update as frequently
 * 
 * Module icons are grabbed from `module_icon_016.png` in the module's directory.
 * You can place custom setting icons into `files/fonts/icons`.
 * They will be available inside `settings.lua` via a font, use `get_icon(name)` to get the character.
 */

import { writeFileSync, existsSync, readFileSync, readdirSync } from "fs";
import { execSync } from "child_process";
import * as CSV from "csv-parse/sync";
import { basename } from "path";
import * as YAML from "js-yaml";
import sharp from "sharp";

// Icon file inside of each module's dir
const MODULE_ICON_FILE = "module_icon_016.png";

const ICON_SIZE_PX = 16;
const ICON_FONT_HEIGHT_PX = 23;

// Pattern for filtering commits from the credits
const OMIT_FROM_COMMIT_LOG = /^Merge (pull|branch) /;

// Comment banner for fonts
const XML_BANNER = "<!-- Generated by scripts/build.js -->\n";

const LOCALE_KEYS = ["01_en", "02_ru", "03_pt-br", "04_es-es", "05_de", "06_fr-fr", "07_it", "08_pl", "09_zh-cn", "10_jp", "11_ko"];

if (!existsSync("mod.xml")) {
	console.error("Run this in the mod's root directory");
	process.exit(1);
}

const patch = (file, fn) => writeFileSync(file, fn(readFileSync(file, "utf8").trim()));
const ls = (dir) => readdirSync(dir).map((x) => `${dir}/${x}`);

function getWorkshopId() {
	const id = existsSync("workshop_id.txt") && readFileSync("workshop_id.txt", "utf8").trim();
	if (!id || !(/^\d+$/).test(id)) return "0";
	return id;
}

function patchWorkshopId() {
	const id = getWorkshopId();
	if (id == "0") {
		console.error("WARN: Missing/invalid workshop_id.txt! Run this script again after publishing to workshop");
	}

	patch("settings.lua", (s) => s.replace(
		/local _workshop_id = "\d+"/,
		`local _workshop_id = "${id}"`
	));

	writeFileSync(
		"files/fonts/workshop/module_icons.xml",
		readFileSync("files/fonts/module_icons.xml", "utf8").replace(
			/<Texture>.+<\/Texture>/,
			`<Texture>../../workshop/content/881100/${id}/files/fonts/module_icons.png</Texture>`
		)
	);

	console.log("Patched stuff with workshop id =", id);
}

async function patchIcons() {
	let iconId = 65;
	let iconPos = 0;

	const names = new Set();
	const compositeLayers = [];
	const generatedQuadChars = [];
	const generatedIconTable = [];

	/** @type {string[]} */
	const icons = [].concat(
		ls("files/fonts/icons"),
		ls("files/modules").map((x) => `${x}/${MODULE_ICON_FILE}`),
	).filter(existsSync);

	for (const file of icons) {
		const name = basename(
			file.replace(`/${MODULE_ICON_FILE}`, "").replace(/\.png$/, "")
		);

		if (name.includes(".")) {
			console.error("ERROR: Invalid filename", file);
			process.exit(1);
		}

		if (names.has(name)) {
			console.error("ERROR: Duplicated icon name", name, "from", file);
			process.exit(1);
		}

		names.add(name);
		compositeLayers.push({ input: file, left: iconPos, top: 0 });
		generatedQuadChars.push(`<!-- ${name} --><QuadChar id="${iconId}" rect_x="${iconPos}" rect_y="0" width="${ICON_SIZE_PX}" rect_h="${ICON_SIZE_PX}" rect_w="${ICON_SIZE_PX}" offset_x="0" offset_y="0" />`);
		generatedIconTable.push(`${name}="${String.fromCharCode(iconId)}"`);

		iconPos += ICON_SIZE_PX;
		iconId++;
	}

	console.log("Generating a font for", icons.length, "icons", `(${iconPos}x${ICON_FONT_HEIGHT_PX})`);

	await sharp({
		create: {
			width: iconPos,
			height: ICON_FONT_HEIGHT_PX,
			channels: 4,
			background: [0, 0, 0, 0]
		}
	})
		.composite(compositeLayers)
		.png()
		.toFile("files/fonts/module_icons.png");

	patch(
		"files/fonts/module_icons.xml",
		(s) => s
			.replace(/\s*(<!--.+-->\s*)?<QuadChar.*\/>/g, "")
			.replace(
				/\s*(<!--.+-->\s*)?<\/FontData>/,
				`\n\n${XML_BANNER}${generatedQuadChars.join("\n")}\n</FontData>`
			)
	);

	patch("settings.lua", (s) => s.replace(
		/local _icon_chars = .+/,
		`local _icon_chars = {${generatedIconTable.join(",")}}`
	));

	console.log("Generated and patched custom font for settings.lua");
}

function patchLocale() {
	const keys = {};
	const progress = [];
	let idx = 0;

	const localeFile = "files/standard.csv";
	const existing = CSV.parse(readFileSync(localeFile, "utf8"), {
		relaxColumnCount: true,
		relaxQuotes: true,
	});

	for (const code of LOCALE_KEYS) {
		const file = readFileSync(`locale/${code}.yaml`, "utf8");
		const locale = YAML.load(file);
		let translated = 0;

		for (const key in locale) {
			const value = JSON.stringify(locale[key]);

			if (!keys[key]) {
				keys[key] = new Array(LOCALE_KEYS.length).fill("");
				keys[key][idx] = value;
				translated++;
			} else if (keys[key][0] != value) {
				// default locale is encluded at the bottom of each locale for convenience, omit these
				keys[key][idx] = value;
				translated++;
			}
		}

		progress.push([code, translated]);
		idx++;
	}

	const locale = Object.entries(keys).map((x) => `${x[0]},${x[1].join(",")},,,`);

	const missing = [];
	for (const line of existing) {
		const key = line[0];
		if (!keys[key]) {
			missing.push(key);
			locale.push(`${key},${line.slice(1).map((x) => JSON.stringify(x)).join(",")}`);
		}
	}

	writeFileSync(localeFile, locale.join("\n") + "\n");

	console.log("Generated standard.csv with", locale.length, "keys");
	console.log(
		"Translation progress:",
		progress.map((x) => `${x[0]} (${(x[1] / locale.length * 100).toFixed(2)}%)`).join(", ")
	);

	if (missing.length) {
		console.log(`\x1b[33mWARN: standard.csv contains keys that are not present in 01_en.yaml\x1b[0m`);
		console.log(`\x1b[33m${missing.join(", ")}\x1b[0m`);
	}
}

function patchCommits() {
	const commits = new Set(
		execSync(`git --no-pager log --reverse --pretty=format:"%s"`)
			.toString("utf8").trim().split("\n")
			.filter((x) => !OMIT_FROM_COMMIT_LOG.test(x))
	);

	const out = "files/modules/credits/commit_log.txt";
	writeFileSync(out, [...commits].join("\n") + "\n");
	console.log("Written", commits.size, "commits to", out);
}

/** @type {(()=>void|Promise<void>)[]} */
const steps = [
	patchIcons,
	patchLocale,
	patchWorkshopId,
];

/** @type {(()=>void|Promise<void>)[]} */
const releaseSteps = [
	patchCommits,
]

if (process.argv.includes("--release")) {
	console.log("Patching for a mod release\n");
	steps.push(...releaseSteps);
}

for (const step of steps) {
	await step();
	console.log();
}

console.log("Hämis 👍");
